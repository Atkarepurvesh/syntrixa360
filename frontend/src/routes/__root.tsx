function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  // NOTE: This package ships the public marketing site only (/, /pricing, /book-demo).
  // The Auth / CurrentUser / Organization / Access / TeamManagement providers belong to the
  // dashboard (/app/*), whose source (src/hooks/*, src/types/*, src/routes/app/*) is NOT in this
  // repository. When the dashboard is added back, wrap <Outlet /> in those providers again
  // (ideally inside the /app route layout so the marketing pages stay lightweight).
  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      <Toaster position="top-right" richColors />
    </QueryClientProvider>
  );
}
